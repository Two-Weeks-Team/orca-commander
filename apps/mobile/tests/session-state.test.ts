import { acceptHostSnapshot, beginHostSync, createHostSessionState, disconnectHost, sessionIdentity } from '../src/core/session-state';
import { getAttentionQueue, getOverview } from '../src/core/attention';
import type { AgentSnapshot } from '../src/core/types';
let count=0;
function check(value: unknown, message: string): asserts value { count++; if(!value) throw new Error(message); }
const now=Date.parse('2026-11-02T00:00:00Z');
const agent:AgentSnapshot={id:'a',provider:'codex',title:'test',summary:'synthetic',state:'permission',eventType:'permission_request',target:{hostId:'h',worktreeId:'w',terminalId:'t',dispatchId:'d'},updatedAt:new Date(now).toISOString(),requestId:'r',permissionEvidence:'structured_verified'};
const initial=createHostSessionState('h');
const syncing=beginHostSync(initial);
const snapshot={generation:syncing.generation,revision:1,observedAt:now,agents:[agent]};
check(acceptHostSnapshot(initial,snapshot,now)===initial,'disconnected rejects snapshots');
const ready=acceptHostSnapshot(syncing,snapshot,now);
check(ready.phase==='ready' && ready.agents.length===1,'full snapshot becomes ready');
check(getAttentionQueue([...ready.agents]).length===1,'attention visible only with snapshot');
const sameMillisecondEmpty=acceptHostSnapshot(ready,{...snapshot,revision:2,agents:[]},now);
check(sameMillisecondEmpty.agents.length===0,'new revision in same millisecond removes old permission');
check(getAttentionQueue([...sameMillisecondEmpty.agents]).length===0,'same millisecond empty snapshot clears attention');
check(acceptHostSnapshot(sameMillisecondEmpty,{...snapshot,revision:2},now)===sameMillisecondEmpty,'duplicate revision cannot resurrect permission');
check(acceptHostSnapshot(sameMillisecondEmpty,{...snapshot,observedAt:now+1},now+1)===sameMillisecondEmpty,'old revision with later time cannot resurrect permission');
const later=acceptHostSnapshot(sameMillisecondEmpty,{...snapshot,revision:3},now);
check(later.agents.length===1,'new revision at same time can publish a new snapshot');
const offline=disconnectHost(ready);
check(offline.revision===undefined,'disconnect drops old publisher revision');
check(beginHostSync(ready).revision===undefined,'new sync drops old publisher revision');
check(offline.agents[0]?.state==='unknown','disconnect never means done');
check(offline.agents[0]?.requestId===undefined && offline.agents[0]?.permissionEvidence==='missing','disconnect removes actionable request');
check(getOverview([...offline.agents]).done===0,'no ghost completion');
check(getAttentionQueue([...offline.agents]).length===0,'stale permission not actionable');
const syncingAgain=beginHostSync(offline);
check(acceptHostSnapshot(syncingAgain,snapshot,now)===syncingAgain,'previous connection generation ignored');
check(acceptHostSnapshot(syncingAgain,{...snapshot,revision:999},now)===syncingAgain,'high revision cannot override wrong generation');
const restarted=acceptHostSnapshot(syncingAgain,{...snapshot,generation:syncingAgain.generation,revision:0},now);
check(restarted.phase==='ready','new generation accepts fresh revision zero');
for (const revision of [NaN,Infinity,-1,0.5,Number.MAX_SAFE_INTEGER+1]) {
 check(acceptHostSnapshot(syncing,{...snapshot,revision},now)===syncing,'malformed revision refused');
}
// @ts-expect-error untrusted legacy snapshot intentionally lacks the required revision.
check(acceptHostSnapshot(syncing,{generation:syncing.generation,observedAt:now,agents:[]},now)===syncing,'missing revision fails closed');
const zero=acceptHostSnapshot(syncing,{...snapshot,revision:0},now);
check(zero.phase==='ready','first revision may be zero');
check(acceptHostSnapshot(zero,{...snapshot,revision:0,agents:[]},now)===zero,'duplicate revision zero cannot change content');
check(acceptHostSnapshot(ready,{...snapshot,revision:0,observedAt:now+1},now+1)===ready,'lower revision refused despite later timestamp');
check(acceptHostSnapshot(ready,{...snapshot,revision:1,observedAt:now+1},now+1)===ready,'duplicate revision refused despite later timestamp');
const clockBack=acceptHostSnapshot(ready,{...snapshot,revision:2,observedAt:now-1,agents:[]},now);
check(clockBack.agents.length===0,'revision determines order within freshness bounds even if clock goes back');
check(acceptHostSnapshot(ready,{...snapshot,observedAt:now-1},now)===ready,'older snapshot ignored');
check(acceptHostSnapshot(ready,snapshot,now)===ready,'duplicate revision idempotent');
for(const timestamp of [NaN,Infinity,now+1,now-30001]) check(acceptHostSnapshot(syncing,{...snapshot,observedAt:timestamp},now)===syncing,'invalid snapshot time ignored');
check(acceptHostSnapshot(syncing,snapshot,NaN)===syncing,'invalid clock ignored');
check(acceptHostSnapshot(syncing,{...snapshot,agents:[{...agent,target:{...agent.target,hostId:'other'}}]},now)===syncing,'wrong host ignored');
check(acceptHostSnapshot(syncing,{...snapshot,agents:[agent,{...agent,id:'different-card'}]},now)===syncing,'duplicate composite identity with different card IDs ignored');
check(acceptHostSnapshot(syncing,{...snapshot,agents:[agent,{...agent,target:{...agent.target,terminalId:'other'}}]},now)===syncing,'duplicate card ID ignored');
check(acceptHostSnapshot(syncing,{...snapshot,agents:[{...agent,updatedAt:'invalid'}]},now)===syncing,'malformed event date ignored');
check(acceptHostSnapshot(syncing,{...snapshot,agents:[{...agent,updatedAt:new Date(now+1).toISOString()}]},now)===syncing,'future event date ignored');
const empty=acceptHostSnapshot(ready,{generation:ready.generation,revision:2,observedAt:now+1,agents:[]},now+1);
check(empty.phase==='ready' && empty.agents.length===0,'full empty snapshot removes deleted sessions');
const targetBefore=ready.agents[0]?.target.terminalId;
agent.target.terminalId='mutated';
check(ready.agents[0]?.target.terminalId===targetBefore,'caller cannot mutate stored target');
check(sessionIdentity({...agent.target,hostId:'other'})!==sessionIdentity(agent.target),'identity includes host');
check(sessionIdentity({...agent.target,dispatchId:'other'})!==sessionIdentity(agent.target),'identity includes dispatch');
check(sessionIdentity({...agent.target,terminalId:'x|y',worktreeId:'z'})!==sessionIdentity({...agent.target,terminalId:'y',worktreeId:'z|x'}),'identity delimiter safe');
console.log(`PASS: ${count} session reconciliation assertions`);
