import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const require=createRequire(import.meta.url);
const {transformSecureStore}=require('../plugins/with-android-secure-store-commit.js');
const root=new URL('../node_modules/expo-secure-store/',import.meta.url);
assert.equal(JSON.parse(readFileSync(new URL('package.json',root))).version,'55.0.18');
const source=readFileSync(new URL('android/src/main/java/expo/modules/securestore/SecureStoreModule.kt',root),'utf8');
const out=transformSecureStore(source);
assert.match(out,/if \(!saveEncryptedItem\([^\n]+\)\) \{\n\s+throw WriteException/);
assert.match(out,/Constant\("deckPersistentCommitV1"\) \{ true \}/);
assert.equal(transformSecureStore(out),out);
assert.throws(()=>transformSecureStore(out.replace('return prefs.edit()', 'return changedPrefs.edit()')),/source changed/);
assert.throws(()=>transformSecureStore('class NewNativeVersion {}'),/source changed/);
const app=JSON.parse(readFileSync(new URL('../app.json',import.meta.url)));
assert(app.expo.plugins.includes('./plugins/with-android-secure-store-commit.js'));
assert.equal(app.expo.android.package,'io.github.twoweeksteam.orcadeck');
const pkg=JSON.parse(readFileSync(new URL('../package.json',import.meta.url)));
assert(pkg.expo.autolinking.android.buildFromSource.includes('expo-secure-store'));
console.log('PASS: 9 Android secure-store commit plugin assertions (source transform; no native execution)');
