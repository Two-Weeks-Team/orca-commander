import { createAudioArbiter } from '../src/adapters/audio-arbiter';
let checks=0;function check(value:unknown,message:string){checks++;if(!value)throw new Error(message);}
const arbiter=createAudioArbiter();
const initial=arbiter.getSnapshot();
check(initial.kind===null&&arbiter.getSnapshot()===initial,'idle snapshot is cached');
const mic=arbiter.acquire('mic');
check(mic!==null&&arbiter.getSnapshot().kind==='mic','microphone acquires exclusive ownership');
check(arbiter.acquire('speech')===null,'speech cannot overlap microphone');
check(arbiter.acquire('mic')===null,'another microphone cannot overlap microphone');
check(!arbiter.release({} as NonNullable<typeof mic>),'a forged owner cannot release microphone');
check(arbiter.getSnapshot().kind==='mic','foreign release preserves current owner');
check(arbiter.release(mic!),'exact microphone owner releases');
const speech=arbiter.acquire('speech');
check(speech!==null&&arbiter.getSnapshot().kind==='speech','speech acquires after confirmed owner release');
check(!arbiter.release(mic!),'late microphone release cannot clear speech');
check(arbiter.acquire('mic')===null,'microphone cannot overlap speech');
check(arbiter.release(speech!),'exact speech owner releases');
let notifications=0;
const unsubscribe=arbiter.subscribe(()=>{notifications++;});
const removeThrowing=arbiter.subscribe(()=>{throw new Error('view');});
const observed=arbiter.acquire('mic')!;
const busySnapshot=arbiter.getSnapshot();
check(Object.isFrozen(busySnapshot)&&arbiter.getSnapshot()===busySnapshot,'owned snapshot is immutable and cached');
check(notifications===1&&arbiter.acquire('speech')===null,'acquisition publishes once and blocked acquisition does not publish');
check(!arbiter.release({} as typeof observed)&&notifications===1,'foreign release never notifies observers');
const other=createAudioArbiter();const foreign=other.acquire('mic')!;
check(!arbiter.release(foreign)&&arbiter.getSnapshot().kind==='mic','another arbiter lease cannot release this owner');
check(arbiter.release(observed)&&notifications===2,'throwing view cannot prevent exact release or the other observer');
check(arbiter.getSnapshot()===initial,'return to idle reuses the initial cached snapshot');
unsubscribe();removeThrowing();other.release(foreign);
const last=arbiter.acquire('speech')!;arbiter.release(last);
check(notifications===2,'unsubscribed views are not called by later ownership');
console.log(`PASS: ${checks} audio arbiter assertions (pure ownership; no native audio)`);
